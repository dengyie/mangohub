async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const qa = page.dashboardQA;
  const cards = page.locator("[data-node-card]");
  const results = { layouts: [], filters: [], historyRequests: 0, errors: [] };
  await page.waitForTimeout(4200);
  check(qa.requests.filter((r) => r.method === "common:getRecords").length === 0, "History loaded before interaction");
  check(qa.network.filter((url) => url.includes("/api/records/load")).length === 0, "Resource history was eagerly loaded");
  await page.locator("#dashboard-map canvas").waitFor();
  check(await page.getByRole("button", {name:"Node locations",exact:true}).getAttribute("aria-expanded") === "true", "Globe must be visible by default");
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({width,height:900});
    await page.evaluate(() => window.scrollTo(0, 0));
    const layout = await page.evaluate(() => ({width:innerWidth,documentWidth:document.documentElement.scrollWidth,firstCardTop:document.querySelector("[data-node-card]").getBoundingClientRect().top,cardHeight:document.querySelector("[data-node-card]").getBoundingClientRect().height}));
    check(layout.width === layout.documentWidth, `Overflow at ${width}px`);
    check(layout.firstCardTop < 1000, `Globe pushes nodes too far down at ${width}px`);
    const heights = await cards.evaluateAll((elements) => elements.map((element) => element.getBoundingClientRect().height));
    check(new Set(heights).size === 1, `Unequal collapsed cards at ${width}px: ${heights}`);
    results.layouts.push(layout);
    await page.screenshot({path:`/Users/mango/project/codex/.playwright-mcp/mangohub-${width}.png`,fullPage:width === 1440});
  }
  for (const [name, count] of [["Needs attention",4],["Offline",1],["CPU ≥90%",1],["RAM ≥90%",1],["Disk ≥90%",1],["Loss >5%",2],["No data",2],["All",8]]) {
    await page.getByRole("button",{name,exact:true}).click();
    check(await cards.count() === count, `Incorrect filter: ${name}`);
    results.filters.push({name,count});
  }
  const search = page.getByRole("textbox",{name:"Search nodes",exact:true});
  await search.fill("tokyo");
  check(await cards.count() === 1, "Search did not narrow nodes");
  await search.press("/");
  check(await search.inputValue() === "tokyo/", "Slash shortcut hijacked text input");
  await search.press("Escape");
  await page.getByLabel("Group",{exact:true}).selectOption("Production");
  check(await cards.count() === 4, "Group selection failed");
  await search.fill("no-such-node");
  await page.getByRole("button",{name:"Reset filters",exact:true}).click();
  check(await cards.count() === 8, "Reset did not restore all nodes");
  await cards.first().getByRole("button",{name:"Details",exact:true}).click();
  await cards.first().getByText("HTTP availability · 1 hour",{exact:true}).waitFor();
  const recordRequests = qa.requests.filter((r) => r.method === "common:getRecords");
  check(recordRequests.length === 1 && recordRequests[0].params.hours === 1 && recordRequests[0].params.max_count === 4000, "Detail history request was not bounded to one hour");
  check((await cards.first().innerText()).includes("1.09 kH/s"), "Mining metrics lost");
  check((await cards.first().innerText()).includes("CNB-AI-反代"), "CNB host reachability lost");
  check((await cards.first().innerText()).includes("Unreachable"), "Latest failed HTTP sample misreported");
  await cards.first().getByRole("button",{name:"Hide details",exact:true}).click();
  await cards.nth(1).getByRole("button",{name:"Details",exact:true}).click();
  await cards.nth(1).getByText("HTTP availability · 1 hour",{exact:true}).waitFor();
  check(!(await cards.nth(1).innerText()).includes("CNB-AI-反代"), "CNB task leaked to another host");
  await cards.nth(1).getByRole("button",{name:"Hide details",exact:true}).click();
  qa.historyFailure = true;
  await cards.first().getByRole("button",{name:"Details",exact:true}).click();
  await cards.first().getByRole("alert").waitFor();
  qa.historyFailure = false;
  await cards.first().getByRole("button",{name:"Refresh",exact:true}).click();
  await cards.first().getByText("HTTP availability · 1 hour",{exact:true}).waitFor();
  check(await cards.first().getByRole("alert").count() === 0, "History retry did not clear error");
  await cards.first().getByRole("button",{name:"Hide details",exact:true}).click();
  await page.locator("#dashboard-map canvas").waitFor();
  check((await page.locator("#dashboard-map").innerText()).includes("Unknown"), "Map unknown state missing");
  await page.getByRole("button",{name:"Node locations",exact:true}).click();
  check(await page.locator("#dashboard-map").count() === 0, "Map did not unmount");
  await page.getByRole("button",{name:"Table",exact:true}).click();
  await page.getByRole("table").waitFor();
  await page.setViewportSize({width:320,height:900});
  check(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth), "Table caused document overflow");
  await page.getByRole("button",{name:"Grid",exact:true}).click();
  await page.getByRole("combobox",{name:"Node health filters"}).selectOption("offline");
  check(await cards.count() === 1, "Mobile filter failed");
  await cards.first().getByRole("button",{name:"Details",exact:true}).click();
  await cards.first().getByText("HTTP availability · 1 hour",{exact:true}).waitFor();
  check((await cards.first().innerText()).includes("Last report:"), "Offline last-report timestamp missing");
  const link = cards.first().getByRole("link",{name:"London · Offline"});
  await link.click();
  check(page.url().endsWith("#/instance/qa-node-3"), "Offline node navigation blocked");
  results.historyRequests = qa.requests.filter((r) => r.method === "common:getRecords").length;
  results.errors = qa.errors;
  check(qa.errors.length === 0, `Browser console errors: ${qa.errors.join("; ")}`);
  return results;
}
