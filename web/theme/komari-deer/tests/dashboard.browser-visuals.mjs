async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(() => scrollTo(0,0));
  const canvas = page.locator('#dashboard-map canvas');
  await canvas.waitFor();
  const colors = await page.evaluate(() => {
    const css = getComputedStyle(document.body);
    return { background: css.getPropertyValue('--background').trim(), ink: css.getPropertyValue('--foreground').trim(), card: css.getPropertyValue('--card').trim() };
  });
  check(colors.background === '#fbfaf6' && colors.ink === '#11110f' && colors.card === '#f7f6ef', 'Paper palette does not match MangoAPI');
  const images = await page.locator('[data-node-card] img').evaluateAll((elements) => elements.map((img) => ({flag:img.src.includes('/flags/'),w:img.getBoundingClientRect().width,h:img.getBoundingClientRect().height,fit:getComputedStyle(img).objectFit})));
  check(images.every((img) => img.flag ? img.w === 28 && img.h === 18 : img.w === 14 && img.h === 14 && img.fit === 'contain'), 'VPS icon frames differ');
  const rotation = () => canvas.getAttribute('data-rotation');
  const before = await rotation();
  await page.waitForTimeout(250);
  check(await rotation() !== before, 'Globe does not animate by default');
  await page.getByRole('button',{name:'Pause globe rotation',exact:true}).click();
  const stopped = await rotation();
  await page.waitForTimeout(200);
  check(await rotation() === stopped, 'Pause did not stop globe');
  await page.getByRole('button',{name:'Rotate globe right',exact:true}).focus();
  await page.keyboard.press('Enter');
  check(Number(await rotation()) === Number(stopped) + 30, 'Keyboard rotation failed');
  const box = await canvas.boundingBox();
  const beforeDrag = Number(await rotation());
  await page.mouse.move(box.x + box.width / 2,box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 80,box.y + box.height / 2,{steps:4});
  await page.mouse.up();
  check(Number(await rotation()) === beforeDrag - 40, 'Pointer drag failed');
  await page.getByRole('button',{name:/^Japan ·/}).focus();
  await page.keyboard.press('Enter');
  check(await page.locator('.node-map-view__node-links a').count() === 2, 'Region selection lost nodes');
  check((await page.locator('.node-map-view__selection').innerText()).includes('Tokyo'), 'Region selection failed');
  await page.getByRole('button',{name:'Resume globe rotation',exact:true}).click();
  await page.emulateMedia({reducedMotion:'reduce'});
  const reduced = await rotation();
  await page.waitForTimeout(200);
  check(await rotation() === reduced, 'Reduced motion ignored');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.setViewportSize({width:1440,height:700});
  await page.evaluate(() => scrollTo(0,document.body.scrollHeight));
  await page.waitForTimeout(150);
  const offscreen = await rotation();
  await page.waitForTimeout(200);
  check(await rotation() === offscreen, 'Offscreen globe kept animating');
  await page.evaluate(() => scrollTo(0,0));
  await page.waitForTimeout(200);
  check(await rotation() !== offscreen, 'Visible globe did not resume');
  await page.evaluate(() => {
    Object.defineProperty(document,'hidden',{configurable:true,get:()=>true});
    document.dispatchEvent(new Event('visibilitychange'));
  });
  const hidden = await rotation();
  await page.waitForTimeout(200);
  check(await rotation() === hidden, 'Hidden document kept animating');
  await page.evaluate(() => { delete document.hidden; document.dispatchEvent(new Event('visibilitychange')); });
  await page.waitForTimeout(200);
  check(await rotation() !== hidden, 'Document visibility did not resume globe');
  check(page.dashboardQA.errors.length === 0, 'Globe generated browser errors');
  return {colors,images,rotation:true,pause:true,drag:true,keyboard:true,regionSelection:true,reducedMotion:true,offscreen:true,hiddenTab:true};
}
