const frame = (...rows: string[]) => {
  if (rows.length !== PIXEL_CAT_SIZE || rows.some((row) => row.length !== PIXEL_CAT_SIZE)) {
    throw new Error("Pixel cat frames must be 16 by 16");
  }
  return rows;
};

